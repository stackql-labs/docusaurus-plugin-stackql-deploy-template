// Builds a stackql-deploy resource template (.iql) from the SQL examples of
// a StackQL provider resource page. CommonJS with no browser or Node APIs,
// shared by the theme component (bundled for the browser) and the tests.
//
// The input is the code of each example section, as extract.js reads it
// from the rendered page:
//
//   { select, insert, update, replace, delete }   (each a string or absent)
//
// The output is the template, one stackql-deploy anchor per operation the
// page documents, in the order stackql-deploy runs them:
//
//   /*+ exists */            count query on the SELECT example's conditions
//   /*+ create */            the INSERT example
//   /*+ update */            the UPDATE example, else the REPLACE example
//   /*+ statecheck ... */    count query with each settable column = its value
//   /*+ exports */           the SELECT example's columns
//   /*+ delete */            the DELETE example, else the lifecycle delete
//
// Two page formats are read. Pages generated by @stackql/provider-utils
// mark required parameters with `-- required` comments and carry no anchors;
// the awscc pages carry the anchors in their examples and no comments. An
// example that starts with an anchor keeps it; one that does not gets it.

const STATECHECK_HINT = '/*+ statecheck, retries=5, retry_delay=10 */';

// The default route pattern of a resource page: /services/{service}/{resource}.
// The first capture group is the resource name, used for the file name.
const DEFAULT_RESOURCE_ROUTE = '/services/[^/]+/([^/]+)';

/** `sql` with `/*+ <anchor> *\/` in front, unless it starts with an anchor. */
function withAnchor(sql, anchor) {
  return /^\s*\/\*\+/.test(sql) ? sql : `/*+ ${anchor} */\n${sql}`;
}

/** A line split into its SQL and its `--` comment (outside quotes). */
function splitLineComment(line) {
  let quoted = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === "'") quoted = !quoted;
    else if (!quoted && c === '-' && line[i + 1] === '-') {
      return { code: line.slice(0, i), comment: line.slice(i + 2).trim() };
    }
  }
  return { code: line, comment: '' };
}

/** `code` split on the keyword AND, outside quotes. */
function splitOnAnd(code) {
  const parts = [];
  let quoted = false;
  let start = 0;
  for (let i = 0; i < code.length; i++) {
    const c = code[i];
    if (c === "'") quoted = !quoted;
    else if (
      !quoted &&
      /^and$/i.test(code.slice(i, i + 3)) &&
      !/\w/.test(code[i - 1] || '') &&
      !/\w/.test(code[i + 3] || '')
    ) {
      parts.push(code.slice(start, i));
      start = i + 3;
      i += 2;
    }
  }
  parts.push(code.slice(start));
  return parts.map((p) => p.trim()).filter(Boolean);
}

/**
 * The conditions of a WHERE clause, without their comments. When any
 * condition is marked `-- required`, only the marked ones are kept: the
 * others are optional request parameters, which a template should not pin
 * to a value.
 */
function parseConditions(where) {
  const conditions = [];
  for (const line of String(where || '').split('\n')) {
    const { code, comment } = splitLineComment(line);
    const required = /^required\b/i.test(comment);
    for (const condition of splitOnAnd(code)) conditions.push({ condition, required });
  }
  const marked = conditions.some((c) => c.required);
  return conditions.filter((c) => !marked || c.required).map((c) => c.condition);
}

/**
 * Splits a SELECT statement into its select list, table and conditions:
 *   fields     - column names from the SELECT list (`*` dropped)
 *   table      - the fully qualified table after FROM
 *   conditions - the WHERE conditions (see parseConditions)
 */
function parseSelectSql(sql) {
  const selectFromMatch = sql.match(/SELECT\s+([\s\S]+?)\s+FROM\s+/i);
  const fromMatch = sql.match(/FROM\s+(\S+)/i);
  const whereMatch = sql.match(/WHERE\s+([\s\S]+?)(?:\s*;\s*$|$)/i);

  const fields = selectFromMatch
    ? selectFromMatch[1]
        .split(',')
        .map((f) => f.trim())
        .filter((f) => f && f !== '*')
    : [];

  const table = fromMatch ? fromMatch[1] : '';
  const conditions = whereMatch ? parseConditions(whereMatch[1].replace(/;\s*$/, '')) : [];

  return { fields, table, conditions };
}

/** The column list of an `INSERT INTO <table> (...)` statement. */
function parseInsertColumns(sql) {
  const match = sql.match(/INSERT\s+INTO\s+\S+\s*\(([\s\S]+?)\)/i);
  if (!match) return [];
  return match[1]
    .split(',')
    .map((c) => c.trim())
    .filter(Boolean);
}

/** `list` split on commas outside quotes, brackets and {{ }}. */
function splitTopLevel(list) {
  const parts = [];
  let depth = 0;
  let quoted = false;
  let start = 0;
  for (let i = 0; i < list.length; i++) {
    const c = list[i];
    if (c === "'") quoted = !quoted;
    else if (quoted) continue;
    else if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) depth--;
    else if (c === ',' && depth === 0) {
      parts.push(list.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(list.slice(start));
  return parts.map((p) => p.trim()).filter(Boolean);
}

/**
 * The value each column of an `INSERT INTO t (...) SELECT ...` statement is
 * given, by column name: `'{{ name }}'` for a string, `{{ size }}` for a
 * number. Empty when the columns and values do not line up.
 */
function parseInsertValues(sql) {
  const columns = parseInsertColumns(sql);
  const match = sql.match(/\)\s*SELECT\s+([\s\S]+?)(?:\s+RETURNING\b[\s\S]*|\s*;?\s*)$/i);
  if (!columns.length || !match) return {};
  // Block comments (the `/* required */` markers) are not part of a value.
  const values = splitTopLevel(match[1].replace(/;\s*$/, '')).map((v) =>
    v.replace(/\/\*[\s\S]*?\*\//g, '').trim(),
  );
  if (values.length !== columns.length) return {};
  return Object.fromEntries(columns.map((c, i) => [c, values[i]]));
}

function whereLines(conditions, keyword = 'WHERE ') {
  return conditions.length ? `\n${keyword}${conditions.join(' AND\n')}` : '';
}

/** The `exists` query: a count over the SELECT example's conditions. */
function buildExistsQuery(parsed) {
  return `SELECT count(*) as count\nFROM ${parsed.table}${whereLines(parsed.conditions)}\n;`;
}

/**
 * The `statecheck` query: a count where each selected column equals its
 * value (as the INSERT example writes it, else `{{ column }}`), followed by
 * the SELECT example's conditions. Columns already in those conditions (for
 * example `region`) are not repeated.
 */
function buildStatecheckQuery(parsed, values = {}) {
  const conditionColumns = new Set();
  for (const c of parsed.conditions) {
    const match = c.match(/^\s*(\w+)\s*=/);
    if (match) conditionColumns.add(match[1].toLowerCase());
  }
  const fieldConditions = parsed.fields
    .filter((f) => !conditionColumns.has(f.toLowerCase()))
    .map((f) => `${f} = ${values[f] || `{{ ${f} }}`}`);
  const all = [...fieldConditions, ...parsed.conditions];
  return `SELECT count(*) as count\nFROM ${parsed.table}${whereLines(all, 'WHERE \n')}\n;`;
}

/** The `exports` query: the SELECT example's columns except `region`. */
function buildExportsQuery(parsed) {
  const exportFields = parsed.fields.filter((f) => f.toLowerCase() !== 'region');
  return `SELECT\n${exportFields.join(',\n')}\nFROM ${parsed.table}${whereLines(parsed.conditions)};`;
}

/**
 * The template for the sections of one page. Anchors are included only for
 * the operations the page documents; an empty string when it documents none.
 */
function buildTemplate(sections) {
  const parts = [];
  let parsed = null;

  if (sections.select) {
    parsed = parseSelectSql(sections.select);
    parts.push(`/*+ exists */\n${buildExistsQuery(parsed)}`);
  }

  if (sections.insert) {
    parts.push(withAnchor(sections.insert, 'create'));
  }

  const update = sections.update || sections.replace;
  if (update) {
    parts.push(withAnchor(update, 'update'));
  }

  if (parsed) {
    // With an INSERT, the statecheck compares the columns that can be set
    // (skipping read-only columns such as created_at), with the values the
    // INSERT gives them.
    let mutableParsed = parsed;
    let values = {};
    if (sections.insert) {
      const insertColumns = new Set(parseInsertColumns(sections.insert));
      const mutableFields = parsed.fields.filter((f) => insertColumns.has(f));
      if (mutableFields.length > 0) {
        mutableParsed = { ...parsed, fields: mutableFields };
      }
      values = parseInsertValues(sections.insert);
    }
    parts.push(`${STATECHECK_HINT}\n${buildStatecheckQuery(mutableParsed, values)}`);
    parts.push(`/*+ exports */\n${buildExportsQuery(parsed)}`);
  }

  if (sections.delete) {
    parts.push(withAnchor(sections.delete, 'delete'));
  }

  return parts.join('\n\n');
}

/**
 * The resource name in `pathname` per `routePattern` (a regular expression
 * source whose first capture group is the name), or null when the path is
 * not a resource page.
 */
function resourceNameFor(pathname, routePattern = DEFAULT_RESOURCE_ROUTE) {
  const match = String(pathname || '').match(new RegExp(routePattern));
  return match && match[1] ? match[1] : null;
}

module.exports = {
  DEFAULT_RESOURCE_ROUTE,
  STATECHECK_HINT,
  withAnchor,
  splitLineComment,
  splitOnAnd,
  parseConditions,
  parseSelectSql,
  parseInsertColumns,
  parseInsertValues,
  buildExistsQuery,
  buildStatecheckQuery,
  buildExportsQuery,
  buildTemplate,
  resourceNameFor,
};
